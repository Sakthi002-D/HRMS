-- Grade Master (Grade → Position → Designation) for the MPR form, plus the chosen
-- values on manpower_requests. Run once, in one transaction. Safe to re-run:
-- tables/columns use IF NOT EXISTS and the seed skips rows that already exist.
-- Rows are never hard-deleted: HR sets active = FALSE in Settings → Grade Master.

BEGIN;

CREATE TABLE IF NOT EXISTS grades (
    id SERIAL PRIMARY KEY,
    code TEXT NOT NULL UNIQUE,
    band TEXT NOT NULL,
    sort_order INTEGER NOT NULL DEFAULT 0,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS grade_positions (
    id SERIAL PRIMARY KEY,
    grade_id INTEGER NOT NULL REFERENCES grades(id),
    name TEXT NOT NULL,
    sort_order INTEGER NOT NULL DEFAULT 0,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
-- One position name per grade, one designation name per position (case-insensitive)
CREATE UNIQUE INDEX IF NOT EXISTS grade_positions_unique_idx ON grade_positions (grade_id, LOWER(name));

CREATE TABLE IF NOT EXISTS grade_designations (
    id SERIAL PRIMARY KEY,
    position_id INTEGER NOT NULL REFERENCES grade_positions(id),
    name TEXT NOT NULL,
    sort_order INTEGER NOT NULL DEFAULT 0,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS grade_designations_unique_idx ON grade_designations (position_id, LOWER(name));

-- Chosen names saved as text, so old MPRs keep their values if the master changes later.
-- grade already exists (012); the others are new.
ALTER TABLE manpower_requests
ADD COLUMN IF NOT EXISTS grade TEXT,
ADD COLUMN IF NOT EXISTS position TEXT,
ADD COLUMN IF NOT EXISTS designation TEXT,
ADD COLUMN IF NOT EXISTS employee_category TEXT;

